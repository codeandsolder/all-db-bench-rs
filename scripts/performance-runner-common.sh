#!/usr/bin/env bash

COMMON_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=continuous-noise-runner-common.sh
source "$COMMON_DIR/continuous-noise-runner-common.sh"
PERFORMANCE_ADMISSION_POLICY=${PERFORMANCE_ADMISSION_POLICY:-$CONTINUOUS_ADMISSION_POLICY}

performance_check_free_space() {
  local profile=$1 phase=$2 path=${3:-${PERFORMANCE_FREE_SPACE_PATH:-${DATA_DIR:-$PWD}}}
  [[ "$profile" == smoke ]] && return 0
  local min_gib=${CASE_MIN_FREE_GIB:-${PERFORMANCE_MIN_FREE_GIB:-${MIN_FREE_GIB:-8}}} free_kib min_kib
  free_kib=$(df -Pk -- "$path" | awk 'NR==2 {print $4}') || return 2
  min_kib=$(awk -v g="$min_gib" 'BEGIN { if (g < 0) exit 2; printf "%.0f", g * 1024 * 1024 }') || return 2
  if (( free_kib < min_kib )); then
    echo "refusing performance case under low free space ($phase): free_kib=$free_kib required_kib=$min_kib path=$path" >&2
    return 75
  fi
}

performance_check_io_quiet() {
  local profile=$1 phase=$2 threshold=${3:-5.0}
  [[ "$profile" == smoke ]] && return 0
  performance_check_free_space "$profile" "$phase" || return $?
  [[ "${ALLOW_BUSY:-0}" == 1 ]] && return 0
  # A bounded storage profile already fixes the benchmark's resource envelope.
  # Do not deadlock admission on global PSI generated by idle-priority background
  # I/O that should yield once the foreground benchmark actually starts.
  [[ "${DBBENCH_STORAGE_PROFILE_MODE:-}" == bounded ]] && return 0

  # Multi-device hosts can have persistent pressure on an unrelated backing
  # device. When the caller binds admission to the benchmark device, sample
  # that block device directly instead of rejecting on host-global I/O PSI.
  if [[ -n "${PERFORMANCE_IO_QUIET_DEVICE:-}" ]]; then
    local device=${PERFORMANCE_IO_QUIET_DEVICE##*/}
    local stat_path="/sys/class/block/$device/stat"
    local sample_s=${PERFORMANCE_IO_QUIET_SAMPLE_SECONDS:-1}
    local max_iops=${PERFORMANCE_IO_QUIET_MAX_IOPS:-100}
    local max_busy=${PERFORMANCE_IO_QUIET_MAX_BUSY_PERCENT:-10}
    [[ -r "$stat_path" ]] || { echo "I/O admission device stat not readable: $stat_path" >&2; return 2; }
    local r1 _rm1 _rs1 _rt1 w1 _wm1 _ws1 _wt1 _in1 busy1 _weighted1
    local r2 _rm2 _rs2 _rt2 w2 _wm2 _ws2 _wt2 _in2 busy2 _weighted2
    read -r r1 _rm1 _rs1 _rt1 w1 _wm1 _ws1 _wt1 _in1 busy1 _weighted1 _ < "$stat_path"
    sleep "$sample_s"
    read -r r2 _rm2 _rs2 _rt2 w2 _wm2 _ws2 _wt2 _in2 busy2 _weighted2 _ < "$stat_path"
    local iops busy_pct
    iops=$(awk -v d="$(((r2-r1)+(w2-w1)))" -v s="$sample_s" 'BEGIN { printf "%.3f", d/s }') || return 2
    busy_pct=$(awk -v d="$((busy2-busy1))" -v s="$sample_s" 'BEGIN { printf "%.3f", d/(s*1000)*100 }') || return 2
    if ! awk -v i="$iops" -v mi="$max_iops" -v b="$busy_pct" -v mb="$max_busy" 'BEGIN { exit !(i<=mi && b<=mb) }'; then
      echo "refusing performance case under device I/O activity ($phase): device=$PERFORMANCE_IO_QUIET_DEVICE iops=$iops busy=${busy_pct}% limits=${max_iops}iops/${max_busy}%" >&2
      return 75
    fi
    return 0
  fi

  local pressure
  pressure=$(awk '/^full / {for(i=1;i<=NF;i++) if($i ~ /^avg10=/){split($i,a,"="); print a[2]}}' /proc/pressure/io)
  if ! awk -v p="${pressure:-0}" -v t="$threshold" 'BEGIN{exit !(p<=t)}'; then
    echo "refusing performance case under I/O pressure ($phase): ${pressure}%" >&2
    return 75
  fi
}

performance_check_external_noise() {
  local root=$1 profile=$2 phase=$3 evidence=$4 rc
  [[ "$profile" == smoke || "${ALLOW_EXTERNAL_NOISE:-0}" == 1 ]] && return 0
  continuous_noise_prepare_benchctl "$root" || return $?
  if "$CONTINUOUS_NOISE_BENCHCTL" check-external-noise --json-out "$evidence"; then rc=0; else rc=$?; fi
  if (( rc != 0 )); then
    echo "refusing performance case due to external host work ($phase)" >&2
  fi
  return "$rc"
}

performance_prepare_order() {
  local run_dir=$1 resume_policy=$2
  shift 2
  local -a jobs=("$@")
  local expected existing
  if [[ -s "$run_dir/jobs.txt" ]]; then
    expected=$(mktemp); existing=$(mktemp)
    printf '%s\n' "${jobs[@]}" | sort > "$expected"
    sort "$run_dir/jobs.txt" > "$existing"
    if ! cmp -s "$expected" "$existing"; then
      rm -f "$expected" "$existing"
      echo "refusing performance resume: jobs.txt changed" >&2
      return 2
    fi
    rm -f "$expected" "$existing"
    mapfile -t ORDERED < "$run_dir/jobs.txt"
  else
    mapfile -t ORDERED < <(printf '%s\n' "${jobs[@]}" | shuf)
    printf '%s\n' "${ORDERED[@]}" > "$run_dir/jobs.txt"
  fi
  if [[ "$resume_policy" == reshuffle-remaining ]]; then
    mapfile -t ORDERED < <(printf '%s\n' "${ORDERED[@]}" | shuf)
  fi
}

